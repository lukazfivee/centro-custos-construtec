// Rebuild the inline Worker assets from their reviewable HTML/CSS/JS sources.
const fs=require('node:fs'),path=require('node:path');
const dir=path.join(__dirname,'../cloudflare/center-container/chamados/worker');
const source=[['adminDocument','admin-page.html'],['adminStyles','admin-page.css'],['adminScript','admin-ui.js']];
const output='// Generated by scripts/build-chamados-central-assets.cjs; edit source files instead.\n'
 +source.map(([name,file])=>'export const '+name+' = '+JSON.stringify(fs.readFileSync(path.join(dir,file),'utf8'))+';').join('\n')+'\n';
fs.writeFileSync(path.join(dir,'admin-assets.js'),output);
fs.writeFileSync(path.join(dir,'navigation-assets.js'),'// Generated from navigation-ui.js.\nexport const navigationScript='+JSON.stringify(fs.readFileSync(path.join(dir,'navigation-ui.js'),'utf8'))+';\n');
const entry=[['entryDocument','entry-page.html'],['entryScript','entry-ui.js']];
fs.writeFileSync(path.join(dir,'entry-assets.js'),'// Generated by scripts/build-chamados-central-assets.cjs.\n'
 +entry.map(([name,file])=>'export const '+name+' = '+JSON.stringify(fs.readFileSync(path.join(dir,file),'utf8'))+';').join('\n')+'\n');
console.log('Chamados assets rebuilt.');
