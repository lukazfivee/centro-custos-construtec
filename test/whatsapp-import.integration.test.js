const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

test('importação registra despesas pendentes, evita duplicação e permite desfazer', async (t) => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'cc-whatsapp-'));
  Object.assign(process.env, {DATABASE_URL:'', PGLITE_DATA_DIR:path.join(dir,'db'), RESTORE_ROOT_DIR:path.join(dir,'restore'), JWT_SECRET:'teste-whatsapp-segredo-32-caracteres', ADMIN_INITIAL_PASSWORD:'senha-teste-123', ADMIN_INITIAL_EMAIL:'admin@teste.local'});
  const { initializeDatabase, closeDatabase, getDb } = require('../db');
  const { createApp } = require('../server');
  let server;
  t.after(async () => { if (server) await new Promise(r => server.close(r)); await closeDatabase(); fs.rmSync(dir,{recursive:true,force:true}); });
  await initializeDatabase();
  server = createApp().listen(0, '127.0.0.1');
  await new Promise(r => server.once('listening',r));
  const base = `http://127.0.0.1:${server.address().port}/api`;
  let token;
  async function call(url, method='GET', body) {
    const res = await fetch(base+url, {method,headers:{Authorization:`Bearer ${token}`,'Content-Type':'application/json'},body:body === undefined ? undefined : JSON.stringify(body)});
    return {status:res.status, body:await res.json()};
  }
  token = (await call('/auth/login','POST',{email:'admin@teste.local',senha:'senha-teste-123'})).body.token;
  const category = (await call('/categorias')).body.find(c => c.nome === 'Material').id;
  const texto = 'PAGAMENTO FORNECEDOR A\nR$ 100,00 - CABO\nCENTRO DE CUSTO: OBRA EXEMPLO';
  const itens = [{bloco:1,linha:1,descricao:'CABO',centro:'OBRA EXEMPLO',valor_texto:'R$ 100,00',categoria_id:category,fornecedor:'Fornecedor A'}];
  const malformed = await call('/importacoes/whatsapp','POST',{texto,itens:[null]});
  assert.equal(malformed.status,400);
  const missing = await call('/importacoes/whatsapp','POST',{texto,itens:[]});
  assert.equal(missing.body.pendencias.length,1);
  assert.equal((await call(`/importacoes/whatsapp/${missing.body.importId}`)).body.pendencias.length,1);
  const first = await call('/importacoes/whatsapp','POST',{texto,itens});
  assert.equal(first.status,201, JSON.stringify(first.body));
  assert.equal(first.body.lancados.length,1);
  const historico = await call('/importacoes/whatsapp');
  assert.ok(historico.body.some(i => i.id === first.body.importId));
  const detalhe = await call(`/importacoes/whatsapp/${first.body.importId}`);
  assert.equal(detalhe.status,200); assert.equal(detalhe.body.lancados[0].descricao,'CABO');
  assert.equal(detalhe.body.lancados[0].itemId,first.body.lancados[0].itemId);
  const row = (await getDb().query('SELECT financial_status,amount FROM transactions WHERE id=$1',[first.body.lancados[0].id])).rows[0];
  assert.equal(row.financial_status,'pendente'); assert.equal(Number(row.amount),100);
  const replay = await call('/importacoes/whatsapp','POST',{texto,itens});
  assert.equal(replay.status,201);
  assert.equal((await getDb().query('SELECT count(*)::int n FROM transactions')).rows[0].n,1);
  const adminToken = token;
  const bcrypt = require('bcryptjs');
  const password = await bcrypt.hash('senha-teste-123', 4);
  await getDb().query("INSERT INTO users(name,email,password_hash,role,suite_role,all_cost_centers) VALUES($1,$2,$3,'supervisor',$4,true)", ['Financeiro','financeiro@teste.local',password,'financeiro']);
  token = (await call('/auth/login','POST',{email:'financeiro@teste.local',senha:'senha-teste-123'})).body.token;
  const otherReplay = await call('/importacoes/whatsapp','POST',{texto,itens});
  assert.equal(otherReplay.body.lancados.length,0); assert.match(otherReplay.body.pendencias[0].motivo,/importad/);
  const unknown = await call('/importacoes/whatsapp','POST',{texto:'R$ 42,00 - TUBO\nCENTRO DE CUSTO: CENTRO NOVO',itens:[{bloco:1,linha:1,descricao:'TUBO',centro:'CENTRO NOVO',valor_texto:'R$ 42,00',categoria_id:category}]});
  assert.equal(unknown.status,201); assert.equal(unknown.body.lancados.length,0); assert.match(unknown.body.pendencias[0].motivo,/admin ou gestor/);
  assert.equal((await call(`/importacoes/whatsapp/${first.body.importId}`,'DELETE')).status,404);
  await getDb().query("INSERT INTO users(name,email,password_hash,role,suite_role,all_cost_centers) VALUES($1,$2,$3,'supervisor',$4,false)", ['Tecnico','tecnico@teste.local',password,'tecnico']);
  token = (await call('/auth/login','POST',{email:'tecnico@teste.local',senha:'senha-teste-123'})).body.token;
  assert.equal((await call('/importacoes/whatsapp','POST',{texto,itens})).status,403);
  await getDb().query("INSERT INTO users(name,email,password_hash,role,suite_role,all_cost_centers) VALUES($1,$2,$3,'supervisor',$4,false)", ['Engenharia','engenharia@teste.local',password,'engenharia']);
  token = (await call('/auth/login','POST',{email:'engenharia@teste.local',senha:'senha-teste-123'})).body.token;
  const scoped = await call('/importacoes/whatsapp','POST',{texto,itens});
  assert.equal(scoped.body.lancados.length,0); assert.match(scoped.body.pendencias[0].motivo,/Sem acesso/);
  token = adminToken;
  await getDb().query("UPDATE transactions SET financial_status='liquidado' WHERE id=$1",[first.body.lancados[0].id]);
  const paid = await call(`/importacoes/whatsapp/${first.body.importId}`,'DELETE');
  assert.equal(paid.body.removidos,0); assert.equal(paid.body.pendencias.length,1);
  await getDb().query("UPDATE transactions SET financial_status='pendente' WHERE id=$1",[first.body.lancados[0].id]);
  const { todayIso } = require('../lib/dates');
  const [year,month] = todayIso().split('-').map(Number);
  await getDb().query('INSERT INTO monthly_closings(year,month,closed_by) VALUES($1,$2,1)',[year,month]);
  const closedImport = await call('/importacoes/whatsapp','POST',{texto:'R$ 21,00 - TUBO\nCENTRO DE CUSTO: OBRA EXEMPLO',itens:[{linha:1,bloco:1,valor_texto:'R$ 21,00',descricao:'TUBO',centro:'OBRA EXEMPLO',categoria_id:category}]});
  assert.match(closedImport.body.pendencias[0].motivo,/fechada/);
  const closed = await call(`/importacoes/whatsapp/${first.body.importId}`,'DELETE');
  assert.equal(closed.body.removidos,0); assert.equal(closed.body.pendencias.length,1);
  await getDb().query('DELETE FROM monthly_closings WHERE year=$1 AND month=$2',[year,month]);
  const undo = await call(`/importacoes/whatsapp/${first.body.importId}`,'DELETE');
  assert.equal(undo.status,200,JSON.stringify(undo.body));
  assert.ok((await getDb().query('SELECT deleted_at FROM transactions WHERE id=$1',[first.body.lancados[0].id])).rows[0].deleted_at);
  const center = await getDb().query('SELECT active FROM cost_centers WHERE id=$1',[first.body.centrosCriados[0].id]);
  assert.equal(center.rows[0].active,false);
  assert.equal(undo.body.centrosInativados.length,1);
  const rateioTexto = 'PAGAMENTO FORNECEDOR B\nR$ 300,00\nDESTINO UM – CABO – R$ 100,00\nDESTINO DOIS – TUBO – R$ 150,00\nDESTINO TRES – PECA – R$ 50,00';
  const rateioItens = [['DESTINO UM','CABO','R$ 100,00'],['DESTINO DOIS','TUBO','R$ 150,00'],['DESTINO TRES','PECA','R$ 50,00']].map(([centro,descricao,valor_texto],i)=>({bloco:2,linha:i+1,centro,descricao,valor_texto,total_bloco_texto:'R$ 300,00',categoria_id:category,fornecedor:'FORNECEDOR B'}));
  const partial = await call('/importacoes/whatsapp','POST',{texto:rateioTexto,itens:rateioItens.slice(0,2)});
  assert.equal(partial.body.lancados.length,0); assert.ok(partial.body.pendencias.length >= 3);
  const rateio = await call('/importacoes/whatsapp','POST',{texto:rateioTexto,itens:rateioItens});
  assert.equal(rateio.body.lancados.length,3,JSON.stringify(rateio.body));
  assert.equal(rateio.body.pendencias.length,0);
  const onlyOne = await call(`/importacoes/whatsapp/${rateio.body.importId}/itens/${rateio.body.lancados[0].itemId}`,'DELETE');
  assert.equal(onlyOne.body.removidos,1);
  assert.equal((await getDb().query('SELECT count(*)::int AS n FROM transactions WHERE deleted_at IS NULL')).rows[0].n,2);
  const concurrentText = 'R$ 17,25 - VALVULA\nCENTRO DE CUSTO: DESTINO DOIS';
  const concurrentItem = {bloco:1,linha:1,centro:'DESTINO DOIS',descricao:'VALVULA',valor_texto:'R$ 17,25',categoria_id:category};
  const attempts = await Promise.all([1,2,3].map(() => call('/importacoes/whatsapp','POST',{texto:concurrentText,itens:[concurrentItem]})));
  assert.ok(attempts.every(a => a.status === 201));
  assert.equal((await getDb().query("SELECT count(*)::int n FROM transactions WHERE description='VALVULA'")).rows[0].n,1);
  const parallel = await Promise.all([11,12].map(n => {
    const text = `R$ ${n},00 - MATERIAL ${n}\nCENTRO DE CUSTO: NOVO CONCORRENTE`;
    return call('/importacoes/whatsapp','POST',{texto:text,itens:[{bloco:1,linha:1,centro:'NOVO CONCORRENTE',descricao:`MATERIAL ${n}`,valor_texto:`R$ ${n},00`,categoria_id:category}]});
  }));
  assert.ok(parallel.every(a => a.body.lancados.length === 1),JSON.stringify(parallel));
  assert.equal((await getDb().query("SELECT count(*)::int n FROM cost_centers WHERE name='NOVO CONCORRENTE'")).rows[0].n,1);
  await getDb().query("UPDATE categories SET active=false WHERE lower(name)='outros'");
  const noCategory = await call('/importacoes/whatsapp','POST',{texto:'R$ 19,00 - PARAFUSO\nCENTRO DE CUSTO: DESTINO DOIS',itens:[{...concurrentItem,descricao:'PARAFUSO',valor_texto:'R$ 19,00',categoria_id:999999}]});
  assert.equal(noCategory.body.lancados.length,0); assert.match(noCategory.body.pendencias[0].motivo,/Categoria/);


});

