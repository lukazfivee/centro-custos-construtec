// Generate reviewable, deterministic public assets for the Central Worker overlay.
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const root = path.join(__dirname, '..');
const source = [['suiteDocument', 'index.html'], ['suiteStyles', 'suite.css'], ['suiteScript', 'suite.js']];
const output = '// Generated by scripts/build-suite-launcher.cjs; edit public/suite/* instead.\n'
  + source.map(([name, file]) => 'export const ' + name + ' = '
    + JSON.stringify(fs.readFileSync(path.join(root, 'public/suite', file), 'utf8')) + ';').join('\n') + '\n';
const target = path.join(root, 'cloudflare/center-container/chamados/worker/suite-launcher-assets.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Suite launcher assets are stale.');
} else fs.writeFileSync(target, output);
console.log(JSON.stringify({ ok: true, mode: process.argv.includes('--check') ? 'check' : 'build',
  bytes: Buffer.byteLength(output), sha256: crypto.createHash('sha256').update(output).digest('hex') }));
